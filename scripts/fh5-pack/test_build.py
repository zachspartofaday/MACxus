"""Offline build-input contracts; no compiler, Wine, network, account or game."""
import importlib.util, tempfile, unittest
from pathlib import Path
spec=importlib.util.spec_from_file_location('fh5_build',Path(__file__).with_name('build.py'))
build=importlib.util.module_from_spec(spec);spec.loader.exec_module(build)
class Inputs(unittest.TestCase):
    def test_header_path_is_provenance_only_and_abi_bytes_are_kept(self):
        with tempfile.TemporaryDirectory() as name:
            root=Path(name);a=root/'a.h';b=root/'b.h'
            template='/*** Autogenerated by WIDL 11.0 from %sdlls/xgameruntime/xstore.idl - Do not edit ***/\nstruct ABI { int x; };\n'
            a.write_text(template%'/one/SDK path/');b.write_text(template%'../../different-source/')
            expected=build.sdk_digest(a,'dlls/xgameruntime/xstore.h')
            self.assertEqual(expected,build.sdk_digest(b,'dlls/xgameruntime/xstore.h'))
            b.write_text((template%'../../different-source/').replace('int x','long long x'))
            self.assertNotEqual(expected,build.sdk_digest(b,'dlls/xgameruntime/xstore.h'))
            with self.assertRaises(ValueError):build.sdk_digest(a,'dlls/xgameruntime/xuser.h')
    def test_unknown_header_and_changed_binary_resource_are_rejected_or_distinct(self):
        with tempfile.TemporaryDirectory() as name:
            p=Path(name)/'input';p.write_bytes(b'not a WIDL header')
            with self.assertRaises(ValueError):build.sdk_digest(p,'include/windows.data.json.h')
            first=build.sdk_digest(p,'classes_r.res');p.write_bytes(b'changed resource')
            self.assertNotEqual(first,build.sdk_digest(p,'classes_r.res'))
if __name__=='__main__':unittest.main()
